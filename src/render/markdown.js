function text(value) {
  // workflow-derived text can carry markdown structure and raw HTML:
  // neutralize both, and fold newlines so nothing can start a new line
  return String(value)
    .replace(/\r?\n/g, ' ')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/([\\`|[\]*_"~])/g, '\\$1');
}

function cell(value) {
  return text(value).replaceAll('|', '\\|');
}

export function renderMarkdown(report) {
  const lines = [];
  const { summary } = report;

  lines.push('# n8n-audit report');
  lines.push('');
  lines.push(
    `Scanned ${summary.filesScanned} JSON files. Audited ${summary.workflowsAudited} workflows, ` +
      `skipped ${summary.skippedFiles}. Min score ${report.minScore}, ${summary.belowMinScore} below.`
  );
  lines.push('');

  if (report.workflows.length > 0) {
    lines.push('| Score | Workflow | File | Error | Cred | Naming | Cmplx | Hygiene |');
    lines.push('| ----- | -------- | ---- | ----- | ---- | ------ | ----- | ------- |');
    for (const workflow of report.workflows) {
      const byId = Object.fromEntries(
        workflow.categories.map((category) => [category.id, category.score])
      );
      lines.push(
        `| ${workflow.score} | ${cell(workflow.name)} | ${cell(workflow.file)} | ` +
          `${byId['error-handling']} | ${byId['credential-hygiene']} | ${byId.naming} | ` +
          `${byId.complexity} | ${byId.hygiene} |`
      );
    }
    lines.push('');
  }

  for (const workflow of report.workflows) {
    lines.push(`## ${workflow.score}/100 ${text(workflow.name)}`);
    lines.push('');
    lines.push(`File: ${text(workflow.file)}`);
    lines.push('');
    for (const category of workflow.categories) {
      lines.push(`### ${category.label} ${category.score}/${category.max}`);
      lines.push('');
      if (category.findings.length === 0) {
        lines.push('- No findings.');
      } else {
        for (const finding of category.findings) {
          const line = `${finding.node ? `'${text(finding.node)}' ` : ''}${text(finding.detail)}.`;
          lines.push(`- ${line.charAt(0).toUpperCase()}${line.slice(1)}`);
        }
      }
      lines.push('');
      lines.push(`Recommendation: ${category.recommendation}`);
      lines.push('');
    }
  }

  if (report.skipped.length > 0) {
    lines.push('## Skipped files');
    lines.push('');
    for (const item of report.skipped) {
      lines.push(`- ${cell(item.file)}: ${text(item.reason)}`);
    }
    lines.push('');
  }

  lines.push(`Generated by n8n-audit ${report.version} on ${report.generatedAt}.`);
  lines.push('');

  return lines.join('\n');
}
