const CATEGORY_SHORT = {
  'error-handling': 'Error',
  'credential-hygiene': 'Cred',
  naming: 'Naming',
  complexity: 'Cmplx',
  hygiene: 'Hygiene',
};

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function band(score) {
  if (score >= 80) return 'good';
  if (score >= 50) return 'warn';
  return 'bad';
}

const CSS = `
:root { color-scheme: light dark; }
body { font-family: system-ui, -apple-system, sans-serif; line-height: 1.5;
  margin: 2rem auto; max-width: 60rem; padding: 0 1rem; color: #1a202c; }
h1 { font-size: 1.6rem; }
h2 { margin-top: 2.5rem; border-bottom: 1px solid #cbd5e0; padding-bottom: .3rem; }
h3 { font-size: 1rem; margin-bottom: .3rem; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0; }
th, td { text-align: left; padding: .35rem .6rem; border-bottom: 1px solid #e2e8f0; }
th { border-bottom: 2px solid #cbd5e0; }
.score { font-weight: 700; }
.good { color: #167d3f; }
.warn { color: #9a6700; }
.bad { color: #b42318; }
.meta { color: #4a5568; font-size: .9rem; }
ul { margin: .3rem 0; padding-left: 1.2rem; }
li { margin: .15rem 0; }
.rec { background: #edf2f7; border-left: 3px solid #a0aec0; padding: .4rem .8rem;
  margin: .5rem 0 1.2rem 0; }
footer { color: #718096; font-size: .85rem; margin-top: 3rem; }
`;

export function renderHtml(report) {
  const { summary } = report;
  const parts = [];

  parts.push('<!DOCTYPE html>');
  parts.push('<html lang="en">');
  parts.push('<head>');
  parts.push('<meta charset="utf-8">');
  parts.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  parts.push(`<title>n8n-audit report</title>`);
  parts.push(`<style>${CSS}</style>`);
  parts.push('</head>');
  parts.push('<body>');
  parts.push('<h1>n8n-audit report</h1>');
  parts.push(
    `<p>Scanned ${summary.filesScanned} JSON files. Audited ${summary.workflowsAudited} ` +
      `workflows, skipped ${summary.skippedFiles}. Min score ${report.minScore}, ` +
      `${summary.belowMinScore} below.</p>`
  );

  if (report.workflows.length > 0) {
    parts.push('<table>');
    parts.push('<thead><tr><th>Score</th><th>Workflow</th><th>File</th>');
    for (const id of Object.keys(CATEGORY_SHORT)) {
      parts.push(`<th>${CATEGORY_SHORT[id]}</th>`);
    }
    parts.push('</tr></thead>');
    parts.push('<tbody>');
    for (const workflow of report.workflows) {
      const byId = Object.fromEntries(
        workflow.categories.map((category) => [category.id, category.score])
      );
      parts.push(
        `<tr><td class="score ${band(workflow.score)}">${workflow.score}</td>` +
          `<td>${escapeHtml(workflow.name)}</td><td>${escapeHtml(workflow.file)}</td>` +
          Object.keys(CATEGORY_SHORT)
            .map((id) => `<td class="${band((byId[id] / 20) * 100)}">${byId[id]}</td>`)
            .join('') +
          '</tr>'
      );
    }
    parts.push('</tbody>');
    parts.push('</table>');
  }

  for (const workflow of report.workflows) {
    parts.push('<section>');
    parts.push(
      `<h2><span class="score ${band(workflow.score)}">${workflow.score}/100</span> ` +
        `${escapeHtml(workflow.name)}</h2>`
    );
    parts.push(`<p class="meta">File: ${escapeHtml(workflow.file)}</p>`);
    for (const category of workflow.categories) {
      parts.push(
        `<h3>${escapeHtml(category.label)} ` +
          `<span class="score ${band((category.score / category.max) * 100)}">` +
          `${category.score}/${category.max}</span></h3>`
      );
      parts.push('<ul>');
      if (category.findings.length === 0) {
        parts.push('<li>No findings.</li>');
      } else {
        for (const finding of category.findings) {
          if (finding.node) {
            const rest = ` ${finding.detail}.`;
            parts.push(
              `<li><strong>${escapeHtml(finding.node)}</strong>${escapeHtml(rest)}</li>`
            );
          } else {
            const text = `${finding.detail}.`;
            const shown = text.charAt(0).toUpperCase() + text.slice(1);
            parts.push(`<li>${escapeHtml(shown)}</li>`);
          }
        }
      }
      parts.push('</ul>');
      parts.push(`<p class="rec">Recommendation: ${escapeHtml(category.recommendation)}</p>`);
    }
    parts.push('</section>');
  }

  if (report.skipped.length > 0) {
    parts.push('<section>');
    parts.push('<h2>Skipped files</h2>');
    parts.push('<ul>');
    for (const item of report.skipped) {
      parts.push(`<li>${escapeHtml(item.file)}: ${escapeHtml(item.reason)}</li>`);
    }
    parts.push('</ul>');
    parts.push('</section>');
  }

  parts.push(
    `<footer>Generated by n8n-audit ${escapeHtml(report.version)} on ` +
      `${escapeHtml(report.generatedAt)}.</footer>`
  );
  parts.push('</body>');
  parts.push('</html>');
  parts.push('');

  return parts.join('\n');
}
